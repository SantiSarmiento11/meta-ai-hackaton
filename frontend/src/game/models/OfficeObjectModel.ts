export const OFFICE_OBJECTS_MAP = new Map<string, OfficeObjectDefinition>(
  OFFICE_OBJECTS_CATALOG.map((obj) => [obj.id, obj])
);

export function getOfficeObjectById(id: string): OfficeObjectDefinition | undefined {
  return OFFICE_OBJECTS_MAP.get(id);
}

export function getOfficeObjectsByCategory(category: ObjectCategory): OfficeObjectDefinition[] {
  return OFFICE_OBJECTS_CATALOG.filter((obj) => obj.category === category);
}

export function getOfficeObjectsByAtlas(atlasKey: AtlasKey): OfficeObjectDefinition[] {
  return OFFICE_OBJECTS_CATALOG.filter((obj) => obj.atlasKey === atlasKey);
}

export interface GridCell {
  col: number;
  row: number;
}

export function getOccupiedGridCells(
  startCol: number,
  startRow: number,
  footprintWidth: number,
  footprintHeight: number
): GridCell[] {
  const cells: GridCell[] = [];
  for (let c = 0; c < footprintWidth; c++) {
    for (let r = 0; r < footprintHeight; r++) {
      cells.push({ col: startCol + c, row: startRow + r });
    }
  }
  return cells;
}
